#!/usr/bin/env bash
# Install Cytolux as a desktop application for the current user.
#
# Adds the launcher to the applications menu, installs the icons at every size the
# desktop needs, puts a "cytolux" command on PATH, and registers the .fgw workspace
# and .fcs data file types so double-clicking either one opens Cytolux.
#
#   ./install.sh              install or re-install
#   ./install.sh --uninstall  remove everything this script added
#
# Nothing is written outside $HOME and no root access is needed. The application
# code itself is not copied: the launcher points at this checkout, so a git pull
# updates the installed app.

set -euo pipefail

APP_ID="cytolux"
APP_NAME="Cytolux"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY="$HOME/miniconda3/envs/flowgate/bin/python"

DESKTOP_DIR="$HOME/.local/share/applications"
ICON_ROOT="$HOME/.local/share/icons/hicolor"
MIME_DIR="$HOME/.local/share/mime"
BIN_DIR="$HOME/.local/bin"

DESKTOP_FILE="$DESKTOP_DIR/$APP_ID.desktop"
MIME_FILE="$MIME_DIR/packages/$APP_ID.xml"
LAUNCHER="$BIN_DIR/$APP_ID"

say()  { printf '  %s\n' "$*"; }
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

refresh_caches() {
    command -v update-desktop-database >/dev/null 2>&1 && \
        update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
    command -v gtk-update-icon-cache >/dev/null 2>&1 && \
        gtk-update-icon-cache -f -t "$ICON_ROOT" >/dev/null 2>&1 || true
    command -v update-mime-database >/dev/null 2>&1 && \
        update-mime-database "$MIME_DIR" >/dev/null 2>&1 || true
}

# ---------------------------------------------------------------- uninstall
if [[ "${1:-}" == "--uninstall" ]]; then
    echo "Removing $APP_NAME from the desktop."
    rm -f "$DESKTOP_FILE" "$MIME_FILE" "$LAUNCHER"
    rm -f "$ICON_ROOT"/scalable/apps/"$APP_ID".svg
    for d in "$ICON_ROOT"/*/apps; do rm -f "$d/$APP_ID.png"; done
    rm -f "$ICON_ROOT"/scalable/mimetypes/application-x-cytolux-workspace.svg
    refresh_caches
    say "Done. The source tree at $SRC was left alone."
    exit 0
fi

# ---------------------------------------------------------------- checks
echo "Installing $APP_NAME from $SRC"

[[ -f "$SRC/cytolux/app.py" ]] || fail "$SRC does not look like the Cytolux checkout."
[[ -x "$PY" ]] || fail "Python interpreter not found at $PY. Create the flowgate conda environment first."

say "Checking that the app imports."
if ! PYTHONNOUSERSITE=1 "$PY" -c "import cytolux" >/dev/null 2>&1; then
    PYTHONNOUSERSITE=1 "$PY" -c "import cytolux" || true
    fail "Cytolux will not import under $PY. Install its dependencies: $PY -m pip install -e \"$SRC\""
fi

mkdir -p "$DESKTOP_DIR" "$BIN_DIR" "$MIME_DIR/packages" \
         "$ICON_ROOT/scalable/apps" "$ICON_ROOT/scalable/mimetypes"

# ---------------------------------------------------------------- icons
say "Installing icons."
install -m 644 "$SRC/cytolux/icons/cytolux.svg" "$ICON_ROOT/scalable/apps/$APP_ID.svg"
install -m 644 "$SRC/cytolux/icons/cytolux.svg" \
    "$ICON_ROOT/scalable/mimetypes/application-x-cytolux-workspace.svg"
for png in "$SRC"/cytolux/icons/app/cytolux-*.png; do
    size="${png##*cytolux-}"; size="${size%.png}"
    mkdir -p "$ICON_ROOT/${size}x${size}/apps"
    install -m 644 "$png" "$ICON_ROOT/${size}x${size}/apps/$APP_ID.png"
done

# ---------------------------------------------------------------- command on PATH
say "Installing the cytolux command into $BIN_DIR."
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Start Cytolux. Arguments: a .fgw workspace or a folder of FCS files (optional).
# Generated by $SRC/install.sh. Edit the source checkout, not this file.
export PYTHONNOUSERSITE=1
cd "$SRC" && exec "$PY" -m cytolux "\$@"
EOF
chmod 755 "$LAUNCHER"

# ---------------------------------------------------------------- file types
say "Registering the .fgw and .fcs file types."
cat > "$MIME_FILE" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
  <mime-type type="application/x-cytolux-workspace">
    <comment>Cytolux workspace</comment>
    <glob pattern="*.fgw"/>
    <icon name="application-x-cytolux-workspace"/>
  </mime-type>
  <mime-type type="application/vnd.isac.fcs">
    <comment>Flow cytometry standard data</comment>
    <glob pattern="*.fcs"/>
  </mime-type>
</mime-info>
EOF

# ---------------------------------------------------------------- launcher
say "Writing the applications-menu entry."
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=$APP_NAME
GenericName=Flow Cytometry Analysis
Comment=Open FCS files, plot, gate and export statistics
Exec=$LAUNCHER %F
TryExec=$LAUNCHER
Icon=$APP_ID
Terminal=false
Categories=Science;Biology;
Keywords=flow;cytometry;FCS;gating;FACS;immunology;
MimeType=application/x-cytolux-workspace;application/vnd.isac.fcs;
StartupNotify=true
StartupWMClass=$APP_NAME
EOF
chmod 644 "$DESKTOP_FILE"

if command -v desktop-file-validate >/dev/null 2>&1; then
    desktop-file-validate "$DESKTOP_FILE" || fail "The generated .desktop file did not validate."
fi

refresh_caches

command -v xdg-mime >/dev/null 2>&1 && {
    xdg-mime default "$APP_ID.desktop" application/x-cytolux-workspace 2>/dev/null || true
}

# ---------------------------------------------------------------- report
echo
echo "$APP_NAME is installed."
say "Applications menu: search for \"$APP_NAME\"."
say "Terminal: cytolux [workspace.fgw | folder-of-fcs]"
say "Double-clicking a .fgw workspace now opens $APP_NAME."
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo
       say "Note: $BIN_DIR is not on your PATH, so the cytolux command will not"
       say "resolve in a new shell. Add this line to ~/.bashrc:"
       say "    export PATH=\"\$HOME/.local/bin:\$PATH\"" ;;
esac
echo
say "To remove it later: $SRC/install.sh --uninstall"
